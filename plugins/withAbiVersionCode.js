/**
 * Config plugin: a versionCode of its own for each ABI in an F-Droid build.
 *
 * F-Droid builds one APK per ABI, which keeps each one half the size of the
 * APK on GitHub, and every APK it publishes needs a versionCode no other has.
 * So when the build is for F-Droid (`EXPO_PUBLIC_DISTRIBUTION=fdroid`) and
 * names exactly one ABI (`-PreactNativeArchitectures=arm64-v8a`), the code is
 * app.json's times ten plus the ABI's digit: 61 becomes 611, 612 and 613. Its
 * recipe works out the same numbers with `VercodeOperation`.
 *
 * Any other build, the GitHub one included, keeps app.json's code as it is.
 *
 * android/ is in .gitignore and regenerated by prebuild, so this has to be a
 * plugin: an edit to build.gradle by hand would not survive.
 */
const { withAppBuildGradle } = require('@expo/config-plugins');

const ABI_DIGIT = `
// One versionCode per ABI for F-Droid (plugins/withAbiVersionCode.js).
def resonusAbiDigit = {
    if (System.getenv('EXPO_PUBLIC_DISTRIBUTION') != 'fdroid') return null
    def abis = (findProperty('reactNativeArchitectures') ?: '').split(',')*.trim().findAll { it }
    if (abis.size() != 1) return null
    return ['armeabi-v7a': 1, 'arm64-v8a': 2, 'x86_64': 3][abis[0]]
}()
`;

function applyAbiVersionCode(gradle) {
  if (gradle.includes('resonusAbiDigit')) return gradle;
  const out = gradle
    .replace(/\nandroid \{\n/, `${ABI_DIGIT}\nandroid {\n`)
    .replace(
      /versionCode (\d+)/,
      (_, code) => `versionCode(resonusAbiDigit != null ? ${code} * 10 + resonusAbiDigit : ${code})`,
    );
  if (!out.includes('resonusAbiDigit != null')) {
    throw new Error('withAbiVersionCode: versionCode not found in build.gradle');
  }
  return out;
}

module.exports = function withAbiVersionCode(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error('withAbiVersionCode only supports a Groovy build.gradle');
    }
    cfg.modResults.contents = applyAbiVersionCode(cfg.modResults.contents);
    return cfg;
  });
};
